import { z } from 'zod';
import { isValidTimeZone } from '~/lib/time/offset.ts';
import { canonicalZoneId } from './zones.ts';

/**
 * The curated city dataset.
 *
 * Hand-written rather than imported from a geographic database, because the value
 * here is editorial: which 80 cities people actually search for, which aliases they
 * type, and which offsets are worth covering. Every record is validated at build
 * time — a duplicate slug, an unknown IANA zone or an out-of-range coordinate fails
 * the build rather than shipping a broken page.
 *
 * Time zones are the modern IANA names (Asia/Kolkata, Europe/Kyiv), validated by
 * constructing an Intl formatter rather than by membership of
 * `Intl.supportedValuesOf('timeZone')`. That list reports the *legacy* identifier on
 * this runtime — it contains Asia/Calcutta and Europe/Kiev but not their modern
 * spellings — so validating against it literally would reject correct data. See
 * DECISIONS.md D20.
 */

export type City = {
  /** URL-safe, lowercase, hyphenated, ASCII. */
  slug: string;
  /** English display name. */
  name: string;
  /** English country name. */
  country: string;
  /** ISO 3166-1 alpha-2. */
  countryCode: string;
  /** IANA identifier. */
  timeZone: string;
  tier: 'A' | 'B';
  /** City proper, for internal-link ordering only. Never presented as a fact. */
  population: number;
  lat: number;
  lon: number;
  /** Search synonyms and former names. */
  aliases: string[];
};

const citySchema = z.object({
  slug: z
    .string()
    .min(2)
    .max(40)
    .regex(/^[a-z0-9]+(-[a-z0-9]+)*$/, 'slug must be lowercase ASCII words joined by hyphens'),
  name: z.string().min(1).max(60),
  country: z.string().min(1).max(60),
  countryCode: z
    .string()
    .length(2)
    .regex(/^[A-Z]{2}$/),
  timeZone: z.string().refine(isValidTimeZone, 'not an IANA time zone this runtime knows'),
  tier: z.enum(['A', 'B']),
  population: z.number().int().positive(),
  lat: z.number().min(-90).max(90),
  lon: z.number().min(-180).max(180),
  aliases: z.array(z.string().min(1).max(60)).max(6),
});

