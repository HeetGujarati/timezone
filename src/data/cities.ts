function validate(cities: City[]): City[] {
  const parsed = cities.map((city, index) => {
    const result = citySchema.safeParse(city);
    if (!result.success) {
      throw new Error(
        `City ${index} (${city.slug ?? 'unknown'}) is invalid: ${result.error.issues
          .map((issue) => `${issue.path.join('.')} ${issue.message}`)
          .join('; ')}`,
      );
    }
    return result.data;
  });

  const slugs = new Set<string>();
  for (const city of parsed) {
    if (slugs.has(city.slug)) throw new Error(`Duplicate city slug: ${city.slug}`);
    slugs.add(city.slug);
  }

  const tierA = parsed.filter((city) => city.tier === 'A');
  const tierB = parsed.filter((city) => city.tier === 'B');
  if (tierA.length !== 24) throw new Error(`Expected 24 Tier A cities, found ${tierA.length}`);
  if (tierB.length !== 56) throw new Error(`Expected 56 Tier B cities, found ${tierB.length}`);

  return parsed;
}

export const CITIES: readonly City[] = validate(RAW_CITIES);

export const TIER_A: readonly City[] = CITIES.filter((city) => city.tier === 'A');
export const TIER_B: readonly City[] = CITIES.filter((city) => city.tier === 'B');

/**
 * The eight Tier A cities every Tier B city is paired with. Ranked by search
 * volume rather than population — London and New York carry far more conversion
 * intent than Shanghai does, despite the population ordering saying otherwise.
 */
export const TOP_HUB_SLUGS = [
  'new-york',
  'london',
  'los-angeles',
  'tokyo',
  'singapore',
  'sydney',
  'dubai',
  'delhi',
] as const;

export const TOP_HUBS: readonly City[] = TOP_HUB_SLUGS.map((slug) => {
  const city = CITIES.find((candidate) => candidate.slug === slug);
  if (city === undefined) throw new Error(`TOP_HUB_SLUGS references unknown city: ${slug}`);
  return city;
});

const BY_SLUG = new Map(CITIES.map((city) => [city.slug, city]));

export function cityBySlug(slug: string): City | undefined {
  return BY_SLUG.get(slug);
}

/** Every distinct IANA zone the dataset uses. */
export function cityZones(): string[] {
  return [...new Set(CITIES.map((city) => canonicalZoneId(city.timeZone)))];
}

/** Cities grouped by continent, derived from the zone prefix rather than stored twice. */
export function citiesByContinent(): { continent: string; cities: City[] }[] {
  const CONTINENT_LABELS: Record<string, string> = {
    Africa: 'Africa',
    America: 'Americas',
    Asia: 'Asia',
    Atlantic: 'Atlantic',
    Australia: 'Australia',
    Europe: 'Europe',
    Pacific: 'Pacific',
  };

  const groups = new Map<string, City[]>();
  for (const city of CITIES) {
    const prefix = city.timeZone.split('/')[0] ?? 'Other';
    const label = CONTINENT_LABELS[prefix] ?? prefix;
    const list = groups.get(label);
    if (list === undefined) groups.set(label, [city]);
    else list.push(city);
  }

  return [...groups.entries()]
    .map(([continent, cities]) => ({
      continent,
      cities: cities.sort((a, b) => a.name.localeCompare(b.name, 'en')),
    }))
    .sort((a, b) => a.continent.localeCompare(b.continent, 'en'));
}
